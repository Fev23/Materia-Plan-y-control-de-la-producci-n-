# 2. METODOS DE PRONOSTICO Y SELECCION
# ============================================================

def rmse(real, pred):
    return np.sqrt(np.mean(
        (np.array(real, dtype=float) - np.array(pred, dtype=float))**2
    ))

def _pm3(serie, h):
    base = np.mean(serie[-3:])
    return [max(0, round(base))] * h

def _ses(serie, h):
    m = SimpleExpSmoothing(serie).fit(optimized=True)
    return [max(0, round(v)) for v in m.forecast(h)]

def _holt(serie, h):
    m = ExponentialSmoothing(serie, trend='add').fit(optimized=True)
    return [max(0, round(v)) for v in m.forecast(h)]

def _hw(serie, h):
    m = ExponentialSmoothing(
        serie, trend='add', seasonal='add', seasonal_periods=3
    ).fit(optimized=True)
    return [max(0, round(v)) for v in m.forecast(h)]

METODOS = {'PM3': _pm3, 'SES': _ses, 'Holt': _holt, 'HW': _hw}

def seleccionar_metodo(serie):
    train, test = serie[:6], serie[6:]
    errores = {}
    for nombre, fn in METODOS.items():
        try:
            errores[nombre] = rmse(test, fn(train, len(test)))
        except Exception:
            errores[nombre] = float('inf')
    mejor = min(errores, key=errores.get)
    return mejor, errores


# ============================================================
# 3. HORIZONTE MOVIL
#
# Paso 1: ventana t3-t8  -> pronostico inicial (12 periodos)
#         validar t9-t12 contra real -> RMSE
# Paso 2: ventana t3-t12 -> pronostico corregido t13-t24
# ============================================================

def aplicar_horizonte_movil(serie, metodo):
    fn = METODOS[metodo]

    ventana_1   = serie[2:8]           # t3 a t8
    pron_ini    = fn(ventana_1, 12)    # t9 a t20
    real_t9_t12 = serie[8:12]
    rmse_val1   = rmse(real_t9_t12, pron_ini[:4])

    ventana_2   = serie[2:12]          # t3 a t12
    pron_final  = fn(ventana_2, 12)    # t13 a t24

    return {
        'ventana_1':    ventana_1,
        'pron_ini':     pron_ini,
        'rmse_val1':    round(rmse_val1, 2),
        'ventana_2':    ventana_2,
        'pron_final':   pron_final,
    }


# ============================================================
# 4. PLAN DE PRODUCCION PROYECTADO (PCO)
# ============================================================

def calcular_pco(demanda_pron, SS, Io, Q, LT):
    h   = len(demanda_pron)
    inv = [0.0] * (h + 1)
    inv[0] = Io
    PRO = [0] * h
    PCO = [0] * h
    RN  = [0] * h

    for t in range(h):
        inv_disp = inv[t] - demanda_pron[t]
        RN[t]    = max(0, SS - inv_disp)
        if RN[t] > 0:
            PRO[t] = int(np.ceil(RN[t] / Q)) * Q
        inv[t+1] = inv[t] + PRO[t] - demanda_pron[t]
        if t - LT >= 0:
            PCO[t - LT] = PRO[t]

    return PCO, PRO, [round(v, 1) for v in inv[1:]], RN


