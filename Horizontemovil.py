def _borde_fino():
    lado = Side(style='thin', color="BFBFBF")
    return Border(left=lado, right=lado, top=lado, bottom=lado)

def _borde_medio():
    lado = Side(style='medium', color="1F4E79")
    return Border(left=lado, right=lado, top=lado, bottom=lado)

def _hdr(ws, fila, col, valor, bg=C_AZUL_OSC, fg="FFFFFF", bold=True, center=True):
    c = ws.cell(fila, col, valor)
    c.font      = Font(name='Calibri', bold=bold, color=fg, size=10)
    c.fill      = PatternFill("solid", fgColor=bg)
    c.border    = _borde_fino()
    if center:
        c.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
    return c

def _cel(ws, fila, col, valor, bg=BLANCO, bold=False, center=True, color_fuente="000000"):
    c = ws.cell(fila, col, valor)
    c.font      = Font(name='Calibri', bold=bold, color=color_fuente, size=10)
    c.fill      = PatternFill("solid", fgColor=bg)
    c.border    = _borde_fino()
    if center:
        c.alignment = Alignment(horizontal="center", vertical="center")
    return c

def _titulo_seccion(ws, fila, col_ini, col_fin, texto):
    ws.merge_cells(start_row=fila, start_column=col_ini,
                   end_row=fila,   end_column=col_fin)
    c = ws.cell(fila, col_ini, texto)
    c.font      = Font(name='Calibri', bold=True, color=BLANCO, size=11)
    c.fill      = PatternFill("solid", fgColor=C_AZUL_MED)
    c.alignment = Alignment(horizontal="left", vertical="center", indent=1)
    c.border    = _borde_medio()

