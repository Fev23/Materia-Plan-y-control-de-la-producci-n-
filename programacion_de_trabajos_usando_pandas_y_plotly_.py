import heapq
import time
import pandas as pd
import plotly.express as px
import graphviz

times_data = {
    1:  [4, 2, 1],
    2:  [2, 1, 1],
    3:  [4, 6, 2],
    4:  [5, 3, 2],
    5:  [2, 3, 1],
    6:  [7, 5, 3],
    7:  [2, 1, 2],
    8:  [4, 3, 1],
    9:  [5, 4, 2],
    10: [4, 8, 3]
}

def calc_c(seq, data):
    if not seq:
        return 0, 0, 0
    c1, c2, c3 = 0, 0, 0
    for j in seq:
        c1 += data[j][0]
        c2 = max(c1, c2) + data[j][1]
        c3 = max(c2, c3) + data[j][2]
