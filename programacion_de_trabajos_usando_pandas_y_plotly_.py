def calc_c(seq, data):
    if not seq:
        return 0, 0, 0
    c1, c2, c3 = 0, 0, 0
    for j in seq:
        c1 += data[j][0]
        c2 = max(c1, c2) + data[j][1]
        c3 = max(c2, c3) + data[j][2]
    return c1, c2, c3

def bound(seq, unsched, data, c_times):
    if not unsched:
        return c_times[2]
    c1, c2, c3 = c_times
    s1 = sum(data[j][0] for j in unsched)
    s2 = sum(data[j][1] for j in unsched)
    s3 = sum(data[j][2] for j in unsched)
    m23 = min((data[j][1] + data[j][2]) for j in unsched)
    m3 = min(data[j][2] for j in unsched)
    return max(c1 + s1 + m23, c2 + s2 + m3, c3 + s3)

def solve(data):
    jobs = set(data.keys())
    n = len(data)
    heap = []
    ub = float('inf')
    best = []

    for j in jobs:
        c_times = calc_c([j], data)
        b = bound([j], jobs - {j}, data, c_times)
        heapq.heappush(heap, (b, 1, [j]))

    while heap:
        b, l, seq = heapq.heappop(heap)
        if b >= ub:
            continue
        if l == n:
            ub = calc_c(seq, data)[2]
            best = seq
            continue

        unsched = jobs - set(seq)
        c_times = calc_c(seq, data)

        for j in unsched:
            n_seq = seq + [j]
            n_unsched = unsched - {j}
            p1, p2, p3 = data[j]
            c1 = c_times[0] + p1
            c2 = max(c1, c_times[1]) + p2
            c3 = max(c2, c_times[2]) + p3
            n_c = (c1, c2, c3)
            nb = bound(n_seq, n_unsched, data, n_c)
            if nb < ub:
                heapq.heappush(heap, (nb, l + 1, n_seq))

    return best, ub

